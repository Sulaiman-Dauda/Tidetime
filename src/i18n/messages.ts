/**
 * Community translation registry.
 *
 * English (`en`) is the source of truth and lives in `src/lib/i18n.ts`. Every
 * other locale is a block here holding only the keys that differ from English —
 * anything missing falls back to English automatically, so a partial
 * contribution is valid and useful on day one.
 *
 * ## Add or improve a language
 * 1. Copy an existing block (e.g. `es`) under a new BCP-47 code.
 * 2. Translate the values. You can omit keys you're unsure of — they fall back.
 * 3. That's it: the locale is auto-registered (browser negotiation, the `t()`
 *    helper, and the admin locale picker all pick it up from here).
 *
 * Plural keys use ICU MessageFormat. Provide the plural categories your language
 * actually uses (`one`/`other`, plus `=0` for a special "none" copy). ICU falls
 * back to `other` for any category you don't supply, so it's always safe.
 *
 * See docs/EMBED_LIFECYCLE.md is unrelated; translation contribution lives in
 * src/i18n/README.md.
 */

